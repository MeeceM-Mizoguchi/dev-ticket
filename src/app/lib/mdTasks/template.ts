// ── AI用プロンプト ────────────────────────────────────────────────────────

export interface MdTaskPromptContext {
  memberNames: string[];
  /** 既に使われている分類（マスタは無いので、あくまで参考として渡す） */
  categoryNames: string[];
  /** 取り込み先がプロジェクトタスクのときだけ */
  projectName?: string;
  /** "2026/08/03" */
  today: string;
}

/**
 * AI（Claude 等）に渡して、そのまま取り込める .md を書いてもらうためのプロンプト。
 * 書式仕様と、担当者に指定できる名前・既に使われている分類を埋め込む。
 */
export function buildMdTaskPrompt(ctx: MdTaskPromptContext): string {
  const members = ctx.memberNames.length > 0
    ? ctx.memberNames.join(" / ")
    : "（メンバー未設定。担当者の行は書かないこと）";
  const categories = ctx.categoryNames.length > 0
    ? `自由入力。既に使われている分類: ${ctx.categoryNames.join(" / ")}`
    : "自由入力（例: 事務 / 調査 / 環境構築）";

  return `あなたはタスク管理ツールに取り込むタスク一覧を Markdown で作成します。
以下の書式に厳密に従って出力してください。

# 出力のルール

- Markdown そのものを出力する。コードブロック（\`\`\`）で囲まない。前置きや解説も書かない。
- **見出しがタスクのタイトル**になる。何をするのかが一目で分かる短い文にする。
- 見出しの**直後**に \`- キー: 値\` 形式の箇条書きを置く。これがタスクの各項目になる。
- 項目の箇条書きは**連続した行**でまとめて書き、途中に空行や説明文を挟まない。
- 項目の箇条書きが終わったら**空行を1行入れてから**本文を書く。空行より後ろが、そのタスクの**詳細メモ**になる。

# 使えるキーと値

| キー | 値 |
|---|---|
| ステータス | ${MD_TASK_STATUS_LABELS.join(" / ")} |
| 優先度 | ${MD_PRIORITY_LABELS.join(" / ")} |
| 分類 | ${categories} |
| 担当者 | ${members} |
| 開始日 | YYYY/MM/DD 形式 |
| 期限日 | YYYY/MM/DD 形式 |

- 上の6項目は**できる限り埋める**。ただし**根拠なく推測しない**。判断材料が無い項目は、その行ごと省略する（空文字や「未定」とは書かない）。
- 上の表に無いキーは使わない（備考・目的などの独自キーも作らない。書きたいことは本文に書く）。
- 担当者は上に挙げた名前のいずれかを完全一致で書く。該当が無ければその行を省略する。
- 分類は複数付けられる。読点かカンマで区切る（例: \`- 分類: 事務, 調査\`）。

# 詳細メモの書き方

- **2〜4行程度**にとどめる。タスクは軽い記録なので、長い仕様書にしない。
- 書くのは「なぜやるのか」「どうなったら終わりか」「気をつけること」だけ。
- 手順や持ち物のような並列の情報は箇条書きにしてよい。
- 見出し（\`#\` \`##\` \`###\`）は**本文に書かない**。別のタスクとして解釈される。
- 書くことが無ければ本文ごと省略してよい（タイトルだけのタスクでもよい）。

# 親タスクとサブタスク

- 1回で終わるものは \`##\` だけで書く（これが基本）。
- 何回かに分けて進めるものだけ、\`##\` を親にして、その中の作業を \`###\` の**サブタスク**にする。
- \`###\` は必ず直前の \`##\` に属する。\`####\` 以降の階層は作らない（サブタスクは1階層まで）。
- サブタスクにも同じように項目を書く。
- 迷ったら \`##\` だけで書く。無理に階層を作らない。
${ctx.projectName ? `\n# 取り込み先のプロジェクト\n\n${ctx.projectName}\n` : ""}
# 今日の日付

${ctx.today}

# 出力例

${MD_TASK_TEMPLATE}`;
}
