// ── AI用プロンプト ────────────────────────────────────────────────────────

export interface MdPromptContext {
  memberNames: string[];
  /** プロジェクトに登録済みの分類名 */
  categoryNames: string[];
  sprintName?: string;
  /** "2026/08/03" */
  today: string;
}

/**
 * AI（Claude 等）に渡して、そのまま取り込める .md を書いてもらうためのプロンプト。
 * 書式仕様・選択肢・プロジェクトのメンバー名と分類名を埋め込む。
 */
export function buildMdTicketPrompt(ctx: MdPromptContext): string {
  const members = ctx.memberNames.length > 0
    ? ctx.memberNames.join(" / ")
    : "（メンバー未設定。担当者の行は書かないこと）";
  const categories = ctx.categoryNames.length > 0
    ? ctx.categoryNames.join(" / ")
    : "（分類未設定。分類の行は書かないこと）";

  return `あなたはプロジェクト管理ツールに取り込むチケット一覧を Markdown で作成します。
以下の書式に厳密に従って出力してください。

# 出力のルール

- Markdown そのものを出力する。コードブロック（\`\`\`）で囲まない。前置きや解説も書かない。
- **見出しがチケットのタイトル**になる。
- 見出しの**直後**に \`- キー: 値\` 形式の箇条書きを置く。これがチケットの各項目になる。
- 項目の箇条書きは**連続した行**でまとめて書き、途中に空行や説明文を挟まない。
- 項目の箇条書きが終わったら**空行を1行入れてから**本文を書く。空行より後ろの文章・リスト・表は、すべてチケットの**詳細**になる。

# 親チケットと子チケット

- 1つの作業で完結するものは \`##\` だけで書く（これが基本）。
- 複数の作業に分かれるもの（機能単位・改修一式など）だけ、\`##\` を親にして、その配下の作業を \`###\` の**子チケット**にする。
- \`###\` は必ず直前の \`##\` に属する。\`####\` 以降の階層は作らない（子は1階層まで）。
- **子チケットにも親と同じように項目を書く**。子だからといって省略しない。
- 迷ったら \`##\` だけで書く。無理に階層を作らない。

# 使えるキーと値

| キー | 値 |
|---|---|
| ステータス | ${MD_STATUS_LABELS.join(" / ")} |
| 優先度 | ${MD_PRIORITY_LABELS.join(" / ")} |
| 分類 | ${categories} |
| 担当者 | ${members} |
| 開始日 | YYYY/MM/DD 形式 |
| 期限日 | YYYY/MM/DD 形式 |
| 見積工数 | 時間数（半角の整数のみ。例: 4） |

- 上の7項目は**できる限りすべて埋める**。
- ただし**根拠なく推測しない**。判断材料が無い項目は、その行ごと省略する（空文字や「未定」とは書かない）。
- 上の表に無いキーは使わない（備考・目的などの独自キーも作らない。書きたいことは本文に書く）。
- 担当者・分類は上に挙げた名前のいずれかを完全一致で書く。該当が無ければその行を省略する。
${ctx.sprintName ? `\n# 対象スプリント\n\n${ctx.sprintName}\n` : ""}
# 今日の日付

${ctx.today}

# 出力例

${MD_TICKET_TEMPLATE}`;
}
