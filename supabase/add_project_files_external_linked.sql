-- ファイルボックス：Googleドライブのファイルをコピーせず、元のファイルのまま追加する（BRU20-002）
-- Run in: Supabase Dashboard → SQL Editor → New query
-- ============================================================
--
-- ★ コードのデプロイより先にこの SQL を適用すること。
--   未適用のまま「元のファイルのまま追加」を選ぶと、列が無いため登録に失敗する。
--   （「コピーして追加」と既存のファイルは、未適用でも今までどおり動く）

-- ── project_files.external_linked ────────────────────────────
-- true = 保存先へコピーせず、Googleドライブ上の元ファイルをそのまま参照している行。
--   DevTicket は開くだけで、権限の配布・改名・ゴミ箱への移動・リンク共有は行わない
--   （開けるか・編集できるかは Googleドライブ側の共有設定で決まる）。
-- 既存の行はすべて false のままなので、動きは変わらない。
alter table project_files add column if not exists external_linked boolean not null default false;
