-- まとめてマージの途中経過（BRU13-042）。
--
-- まとめてマージは「単独のマージ可否 → 捨てブランチでの試しマージ → 本番のマージ」を
-- サーバー側の1リクエストで通しで走らせる。押してから終わるまで数十秒かかることがあり、
-- その間クライアントには何も返らないため、画面には「マージ中...」としか出せなかった。
--
-- 何をしている最中なのかが読めないと、待つべきなのか壊れているのかが判断できない。
-- そこでサーバーが段ごとに現在地をここへ書き、画面はこの列を数秒おきに引いて出す。
--
--   { "step": "precheck" | "trial" | "merge", "done": 2, "total": 7,
--     "current": 51, "trialSkipped": true }
--
-- 記録は補助なので、この列が無くても実行そのものは従来どおり動く
-- （画面は途中経過が取れないときだけ、これまでどおりの大まかな表示に落ちる）。
alter table github_action_runs add column if not exists progress jsonb;
